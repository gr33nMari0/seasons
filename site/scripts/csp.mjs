// After the build: gives every page a strict content security policy (ADR 0008).
//
// - Inline <script> blocks Starlight keeps (search, the sidebar's scroll position) are allowed by
//   their SHA-256 hash; nothing else inline runs.
// - style="…" attributes become classes in one generated stylesheet (/_astro/attrs.css), loaded
//   last and unlayered, so they win over Starlight's layered styles and style-src stays 'self'.
// - The __CSP__ placeholder Head.astro writes is replaced with the policy. The connect page may also
//   ask DNS-over-HTTPS resolvers, the status service and any https dashboard (questions 336).
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const DIST = join(import.meta.dirname, '../dist')
const CONNECT = ['https:', 'https://cloudflare-dns.com', 'https://dns.google', 'https://api.mcsrvstat.us']

function pages (dir = DIST) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) return pages(path)
    return name.endsWith('.html') ? [path] : []
  })
}

const sha = (text) => `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`
const classes = new Map()

function classFor (style) {
  const decls = style.split(';').map((d) => d.trim()).filter(Boolean)
  const key = decls.join(';')
  if (!classes.has(key)) classes.set(key, `sa-${createHash('sha256').update(key).digest('hex').slice(0, 8)}`)
  return classes.get(key)
}

export function policy (path, scripts) {
  const connect = path.startsWith('/connect/') ? CONNECT.join(' ') : "'self'"
  return [
    "default-src 'self'",
    `script-src 'self' 'wasm-unsafe-eval'${scripts.size ? ' ' + [...scripts].join(' ') : ''}`,
    "style-src 'self'",
    // Starlight draws a few small icons as data: SVG masks in its stylesheet.
    "img-src 'self' data:",
    "font-src 'self'",
    `connect-src ${connect === "'self'" ? "'self'" : "'self' " + connect}`,
    "worker-src 'self'",
    "manifest-src 'self'",
    "frame-src 'none'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'"
  ].join('; ')
}

let count = 0
for (const file of pages()) {
  let html = readFileSync(file, 'utf8')
  const path = '/' + relative(DIST, file).replace(/index\.html$/, '').replace(/\\/g, '/')
  const scripts = new Set()
  for (const m of html.matchAll(/<script(?![^>]*\bsrc=)(?![^>]*type="application\/(?:ld\+)?json")[^>]*>([\s\S]*?)<\/script>/g)) {
    if (m[1].trim()) scripts.add(sha(m[1]))
  }
  // A style attribute becomes a class, added to the element's own class attribute if it has one.
  html = html.replace(/<([a-zA-Z][\w-]*)(\s[^<>]*?)?\sstyle="([^"]*)"([^<>]*)>/g, (all, tag, before = '', style, after) => {
    const cls = classFor(style.replace(/&quot;/g, '"'))
    let attrs = `${before} ${after}`.replace(/\s+$/, '')
    if (/\sclass="/.test(attrs)) attrs = attrs.replace(/\sclass="([^"]*)"/, (_, c) => ` class="${c} ${cls}"`)
    else attrs += ` class="${cls}"`
    return `<${tag}${attrs.replace(/\s+/g, ' ').replace(/ $/, '')}>`
  })
  if (!html.includes('__CSP__')) throw new Error(`${path} has no CSP placeholder`)
  html = html.replace('__CSP__', policy(path, scripts))
  html = html.replace('</head>', '<link rel="stylesheet" href="/_astro/attrs.css"></head>')
  writeFileSync(file, html)
  count++
}

const css = ['/* Generated by scripts/csp.mjs: style attributes moved out of the HTML. */']
for (const [style, cls] of classes) css.push(`.${cls}{${style}}`)
writeFileSync(join(DIST, '_astro/attrs.css'), css.join('\n') + '\n')
console.log(`CSP on ${count} pages; ${classes.size} style attributes moved to classes`)
