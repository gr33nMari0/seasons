const out = ['<!-- SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0 -->',
  '<!-- Seasons\' pixel UI icons, drawn by design/tools/icons.mjs from its grids: edit those, not this',
  '     file. Each is a 16 × 16 symbol filled with the text\'s colour. Use as',
  '     <svg class="icon" aria-hidden="true"><use href="icons.svg#search"/></svg>. -->',
  '<svg xmlns="http://www.w3.org/2000/svg">']

for (const [name, grid] of Object.entries(ICONS)) {
  const rows = grid.trim().split('\n')
  if (rows.length !== 16 || rows.some((r) => r.length !== 16)) throw new Error(`${name}: not 16 × 16`)
  let d = ''
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`
  })
  out.push(`  <symbol id="${name}" viewBox="0 0 16 16"><path fill="currentColor" shape-rendering="crispEdges" d="${d}"/></symbol>`)
}
out.push('</svg>', '')
writeFileSync(join(import.meta.dirname, '../icons.svg'), out.join('\n'))
console.log(`${Object.keys(ICONS).length} icons written to design/icons.svg`)
